document.hidden=false;reduced=true;
occasional();assert.equal(mascot.dataset.emotion,'idle');
reduced=false;open=true;
occasional();assert.equal(mascot.dataset.emotion,'idle');
open=false;dragging=true;
occasional();assert.equal(mascot.dataset.emotion,'idle');
dragging=false;
const button={matches:()=>false,closest:selector=>['.tools-fab-btn','[data-action="tools-fab-toggle"]'].includes(selector)?fab:null};
