import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const source=fs.readFileSync(new URL('../static/app.js',import.meta.url),'utf8');
let reset,occasional,intervalMs,timeoutMs,now=10000,typing=false,reduced=false,open=false,dragging=false;
const attributes={},mascot={dataset:{},matches:selector=>selector==='.nubi-robot',closest:()=>({setAttribute:(key,value)=>attributes[key]=value})};
const events={};
const fab={matches:()=>open||dragging,querySelector:()=>mascot};
const document={hidden:false,activeElement:{matches:()=>typing},documentElement:{classList:{contains:()=>reduced}},body:{classList:{contains:()=>false}},querySelector:selector=>selector==='.tools-fab'?fab:selector==='.tools-fab.is-dragging'?(dragging?fab:null):mascot,addEventListener:(name,listener)=>events[name]=listener};
const scope=vm.createContext({window:{},document,Date:{now:()=>now},matchMedia:()=>({matches:reduced}),
  clearTimeout:()=>{},setTimeout:(fn,ms)=>{reset=fn;timeoutMs=ms;return 1;},setInterval:(fn,ms)=>{occasional=fn;intervalMs=ms;return 1;}});
vm.runInContext(source.slice(source.indexOf('let nubiEmotionTimer;'),source.indexOf('function toolsFabClamp')),scope);
for(const emotion of ['idle','wave','celebrate','sad','think','surprised','turn']){
  scope.setNubiEmotion(emotion);
  assert.equal(mascot.dataset.emotion,emotion);
  assert.equal(attributes['data-emotion'],emotion);
}
reset();assert.equal(mascot.dataset.emotion,'idle');
scope.setNubiEmotion('invalid');assert.equal(mascot.dataset.emotion,'idle');
scope.bindNubiEmotions();
assert.equal(intervalMs,35000);
occasional();assert.equal(mascot.dataset.emotion,'turn');assert.equal(timeoutMs,2500);
events.animationend({target:mascot,animationName:'nubi-body-turn'});
assert.equal(mascot.dataset.emotion,'idle');
occasional();assert.equal(mascot.dataset.emotion,'wave');assert.equal(timeoutMs,2300);
events.animationend({target:mascot,animationName:'nubi-body-wave'});
assert.equal(mascot.dataset.emotion,'idle');
typing=true;
occasional();assert.equal(mascot.dataset.emotion,'idle');
typing=false;document.hidden=true;
